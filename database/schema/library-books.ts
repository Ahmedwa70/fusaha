import { integer, jsonb, pgTable, text, timestamp, uuid } from "drizzle-orm/pg-core";
import type { LocalizedText } from "@/lib/localized-text";

export const libraryBooks = pgTable("library_books", {
  id: uuid("id").primaryKey().defaultRandom(),
  slug: text("slug").notNull().unique(),
  originalTitle: text("original_title").notNull(),
  authors: text("authors").notNull(),
  publisher: text("publisher"),
  publicationYear: integer("publication_year"),
  originalLanguage: text("original_language").notNull().default("ar"),
  isbn: text("isbn"),
  category: text("category").notNull(),
  audience: text("audience").notNull(),
  level: text("level").notNull(),
  skills: jsonb("skills").notNull().default([]).$type<string[]>(),
  displayTitle: jsonb("display_title").notNull().$type<LocalizedText>(),
  description: jsonb("description").notNull().$type<LocalizedText>(),
  longDescription: jsonb("long_description").$type<LocalizedText>(),
  sourceName: text("source_name").notNull(),
  sourceUrl: text("source_url").notNull(),
  destinationType: text("destination_type").notNull(),
  accessStatus: text("access_status").notNull().default("unknown"),
  accessNotes: jsonb("access_notes").$type<LocalizedText>(),
  coverUrl: text("cover_url"),
  coverAlt: jsonb("cover_alt").$type<LocalizedText>(),
  publicationStatus: text("publication_status").notNull().default("draft"),
  reviewStatus: text("review_status").notNull().default("needs_review"),
  lastVerifiedAt: timestamp("last_verified_at", { withTimezone: true }),
  createdBy: uuid("created_by"),
  updatedBy: uuid("updated_by"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  publishedAt: timestamp("published_at", { withTimezone: true }),
});
